// AGP 9 compiles Kotlin itself (built-in Kotlin).  It bundles KGP 2.2.10, so a
// higher kotlin-gradle-plugin has to be put on the buildscript classpath to make
// the compiler (and therefore the Compose compiler plugin) Kotlin 2.4.21.  The
// version catalog is not available inside a buildscript block, so the version is
// repeated here and must stay in sync with `kotlin` in libs.versions.toml.
buildscript {
    repositories {
        google()
        mavenCentral()
    }
    dependencies {
        classpath("org.jetbrains.kotlin:kotlin-gradle-plugin:2.4.21")
    }
}

plugins {
    alias(libs.plugins.android.application) apply false
    alias(libs.plugins.android.library) apply false
    alias(libs.plugins.android.test) apply false
    alias(libs.plugins.baselineprofile) apply false
    alias(libs.plugins.kotlin.compose) apply false
    alias(libs.plugins.kotlin.serialization) apply false
    alias(libs.plugins.ksp) apply false
    alias(libs.plugins.hilt) apply false
    alias(libs.plugins.roborazzi) apply false
}

// `-PskipScreenshots` leaves the Roborazzi-capturing tests out of every module's
// unit test run: a feature-branch push checks the logic without rendering and
// comparing the golden images.  Only tests in the `Screenshot` category are
// dropped, so the behaviour checks that share a screen's test class still run.
// The switch is presence-only, so every other invocation is unchanged.
val skipScreenshots = providers.gradleProperty("skipScreenshots").isPresent

subprojects {
    // The category lives in the design system's test fixtures, so only a module
    // whose test classpath consumes them can hold a tagged test; every other
    // module is left alone (a JUnit category the test runtime cannot load would
    // fail the whole executor).
    afterEvaluate {
        val seesTheFixtures = path == ":core:designsystem" ||
            configurations.findByName("testImplementation")?.dependencies?.any {
                it is ProjectDependency && it.path == ":core:designsystem"
            } == true
        if (skipScreenshots && seesTheFixtures) {
            tasks.withType<Test>().configureEach {
                useJUnit {
                    excludeCategories("com.phonxiety.bridge.designsystem.testing.Screenshot")
                }
            }
        }
    }
}

// ktlint as a formatting-only gate, run through its CLI so it sees exactly the
// same file set for every module and needs no per-module configuration.
val ktlintCli: Configuration = configurations.create("ktlintCli") {
    isCanBeConsumed = false
    isCanBeResolved = true
}

dependencies {
    ktlintCli("com.pinterest.ktlint:ktlint-cli:${libs.versions.ktlint.get()}:all")
}

fun ktlintSources(): FileTree = fileTree(rootDir) {
    include("**/src/**/*.kt")
    // Generated by `mise run phone:iroh`; not hand-editable.
    exclude("**/build/**", "**/src/iroh/**")
}

tasks.register<JavaExec>("ktlintCheck") {
    group = "verification"
    description = "Checks Kotlin formatting with ktlint (formatting only)"
    classpath = ktlintCli
    mainClass.set("com.pinterest.ktlint.Main")
    inputs.files(ktlintSources())
    inputs.file(rootDir.resolve(".editorconfig"))
    // A recorded pass makes the task up to date until a source or the style changes.
    val passed = layout.buildDirectory.file("ktlint/check.passed")
    outputs.file(passed)
    args(ktlintSources().files.map { it.absolutePath })
    doLast { passed.get().asFile.writeText("ok\n") }
}

tasks.register<JavaExec>("ktlintFormat") {
    group = "formatting"
    description = "Formats Kotlin sources with ktlint"
    classpath = ktlintCli
    mainClass.set("com.pinterest.ktlint.Main")
    inputs.files(ktlintSources())
    args(listOf("-F") + ktlintSources().files.map { it.absolutePath })
}
