// AGP 9 compiles Kotlin itself (built-in Kotlin).  It bundles KGP 2.2.10, so a
// higher kotlin-gradle-plugin has to be put on the buildscript classpath to make
// the compiler (and therefore the Compose compiler plugin) Kotlin 2.4.21.  The
// version catalog is not available inside a buildscript block, so the version is
// repeated here and must stay in sync with `kotlin` in libs.versions.toml.
buildscript {
    repositories {
        google()
        mavenCentral()
    }
    dependencies {
        classpath("org.jetbrains.kotlin:kotlin-gradle-plugin:2.4.21")
    }
}

plugins {
    alias(libs.plugins.android.application) apply false
    alias(libs.plugins.android.library) apply false
    alias(libs.plugins.kotlin.compose) apply false
    alias(libs.plugins.kotlin.serialization) apply false
    alias(libs.plugins.ksp) apply false
    alias(libs.plugins.hilt) apply false
    alias(libs.plugins.roborazzi) apply false
    alias(libs.plugins.ktlint) apply false
}

// ktlint as a formatting-only gate.  The Gradle plugin is declared above for
// editor integration; the check itself runs the CLI so it sees exactly the
// same file set for every module and needs no per-module configuration.
val ktlintCli: Configuration by configurations.creating {
    isCanBeConsumed = false
    isCanBeResolved = true
}

dependencies {
    ktlintCli("com.pinterest.ktlint:ktlint-cli:1.8.0:all")
}

fun ktlintSources(): FileTree = fileTree(rootDir) {
    include("**/src/**/*.kt")
    // Generated by `mise run phone:iroh`; not hand-editable.
    exclude("**/build/**", "**/src/iroh/**")
}

tasks.register<JavaExec>("ktlintCheck") {
    group = "verification"
    description = "Checks Kotlin formatting with ktlint (formatting only)"
    classpath = ktlintCli
    mainClass.set("com.pinterest.ktlint.Main")
    inputs.files(ktlintSources())
    args(ktlintSources().files.map { it.absolutePath })
}

tasks.register<JavaExec>("ktlintFormat") {
    group = "formatting"
    description = "Formats Kotlin sources with ktlint"
    classpath = ktlintCli
    mainClass.set("com.pinterest.ktlint.Main")
    inputs.files(ktlintSources())
    args(listOf("-F") + ktlintSources().files.map { it.absolutePath })
}
